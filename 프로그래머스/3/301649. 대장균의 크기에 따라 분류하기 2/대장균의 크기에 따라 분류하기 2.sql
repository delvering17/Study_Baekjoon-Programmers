 SELECT
    T.ID,
    CASE
        WHEN T.PERCENT_SIZE <= 25 THEN 'CRITICAL'
        WHEN T.PERCENT_SIZE <= 50 THEN 'HIGH'
        WHEN T.PERCENT_SIZE <= 75 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS COLONY_NAME
FROM (
    SELECT
        ID,
        CUME_DIST() OVER (ORDER BY SIZE_OF_COLONY DESC) * 100 AS PERCENT_SIZE
    FROM ECOLI_DATA
) AS T
ORDER BY
    T.ID